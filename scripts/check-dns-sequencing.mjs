import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validateDnsReceipt,validateMappingEvidence,validateFreshMapping,guardSha256} from '../operator/qualification-dns.mjs';
const run='11111111-1111-1111-1111-111111111111';
const receipt=(time,ttl=15,address='8.8.8.8')=>({version:1,hostname:'mcp.figma.com',run,guardSha256,method:'node:dns/promises.resolve4(ttl)+lookup; native public guard',resolvers:['synthetic'],observedAt:time,expiresAt:time+ttl*1000,answers:[{address,ttl}]});
const mapping=receipt(1000),fresh=receipt(100000);
assert.throws(()=>validateDnsReceipt(mapping,{run,now:100000}),/Stale/);
assert.deepEqual(validateMappingEvidence(mapping,{run}),['mcp.figma.com:8.8.8.8']);
assert.deepEqual(validateFreshMapping(fresh,{mapping,run,now:114999}),['mcp.figma.com:8.8.8.8']);
assert.throws(()=>validateFreshMapping(fresh,{mapping,run,now:115000}),/Stale/);
assert.throws(()=>validateFreshMapping(receipt(100000,15,'1.1.1.1'),{mapping,run,now:100001}),/DNS changed/);
assert.throws(()=>validateFreshMapping(receipt(100000,15,'127.0.0.1'),{mapping,run,now:100001}),/Non-public/);
assert.throws(()=>validateFreshMapping({...fresh,expiresAt:115001},{mapping,run,now:100001}),/TTL/);
assert.throws(()=>validateFreshMapping(receipt(100000,301),{mapping,run,now:100001}),/Stale/);
const source=fs.readFileSync('operator/seed-selector-lifecycle.mjs','utf8');
assert.ok(source.indexOf('await beforeMutation({dns:draft})')<source.indexOf('validateFreshMapping(fresh'));
assert.ok(source.lastIndexOf('validateFreshMapping(fresh')<source.indexOf('const r=await fetch'));
const shell=fs.readFileSync('operator/approve-qualification-mutations.sh','utf8');
assert.ok(shell.indexOf('collect-fresh-draft-dns.sh')<shell.indexOf('qualification-guard-approval'));
console.log('Offline DNS sequencing: historical mapping separated; exact TTL/cap, drift/private refusal and post-guard POST checks passed. No DNS/network/runtime.');
