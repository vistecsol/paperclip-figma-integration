import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
const host = process.argv[2] ?? '/app';
const path = 'server/src/services/tool-gateway.ts';
const baseline = JSON.parse(readFileSync('host-prerequisite/inspection-baseline.json', 'utf8'));
const original = readFileSync(join(host, path), 'utf8');
if (createHash('sha256').update(original).digest('hex') !== baseline.files[0].sha256) throw new Error('Gateway source drift');
const anchor = '    async executeTool(input: ExecuteGatewayToolInput) {';
if (original.split(anchor).length !== 2) throw new Error('Gateway anchor drift');
const updated = original.replace(anchor, readFileSync('host-prerequisite/inspection-gateway.inc', 'utf8') + anchor);
const scratch = process.env.PAPERCLIP_RUN_SCRATCH_DIR;
if (!scratch) throw new Error('Run scratch required');
const before = join(scratch, 'inspection-before'), after = join(scratch, 'inspection-after');
writeFileSync(before, original); writeFileSync(after, updated);
const result = spawnSync('diff', ['-u', '--label', `a/${path}`, '--label', `b/${path}`, before, after], { encoding: 'utf8' });
if (![0,1].includes(result.status)) throw new Error('diff failed');
writeFileSync('host-prerequisite/figma-inspection.patch', result.stdout.replace(/^ $/gm, ''));
